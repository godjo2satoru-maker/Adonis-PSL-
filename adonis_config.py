def calibrate_single_score(val):
    v = max(1.0, min(8.0, float(val)))
    for (x0, y0), (x1, y1) in zip(CALIBRATION_POINTS, CALIBRATION_POINTS[1:]):
        if v <= x1:
            t = (v - x0) / max(1e-9, x1 - x0)
            return round(y0 + t * (y1 - y0), 1)
    return round(CALIBRATION_POINTS[-1][1], 1)


