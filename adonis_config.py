def rate_range_metric(val, ideal_lo, ideal_hi, close_lo, close_hi, norm_lo, norm_hi):
    if ideal_lo <= val <= ideal_hi:
        return "Идеал", "green"
    if close_lo <= val <= close_hi:
        return "Близко к идеалу", "green"
    if norm_lo <= val <= norm_hi:
        return "В норме", "blue"
    span = max(0.05, norm_hi - norm_lo)
    dist = (norm_lo - val) if val < norm_lo else (val - norm_hi)
    if dist <= span * 0.45:
        return "Зона роста", "amber"
    return "Далеко от идеала", "red"


def rate_min_metric(val, ideal_min, close_min, norm_min):
    if val >= ideal_min:
        return "Идеал", "green"
    if val >= close_min:
        return "Близко к идеалу", "green"
    if val >= norm_min:
        return "В норме", "blue"
    if val >= norm_min - 0.14:
        return "Зона роста", "amber"
    return "Далеко от идеала", "red"


