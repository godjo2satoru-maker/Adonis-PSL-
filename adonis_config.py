PHOTO_HASH_RE = re.compile(r"^(?:wp[0-9a-f]{30}|[pw][0-9a-f]{31}|[0-9a-f]{32})$")


def normalize_gender(gender):
    return "f" if str(gender or "").strip().lower() in ("f", "female", "w", "woman", "ж") else "m"


def make_photo_hash(processed_bytes, gender="m", is_profile=False):
    g = normalize_gender(gender)
    if g == "f":
        if is_profile:
            digest = hashlib.sha256(
                FEMALE_PROFILE_CACHE_VERSION.encode("utf-8") + processed_bytes
            ).hexdigest()[:30]
            return f"wp{digest}"
        digest = hashlib.sha256(
            FEMALE_CACHE_VERSION.encode("utf-8") + processed_bytes
        ).hexdigest()[:31]
        return f"w{digest}"

    if is_profile:
        digest = hashlib.sha256(
            PROFILE_CACHE_VERSION.encode("utf-8") + processed_bytes
        ).hexdigest()[:31]
        return f"p{digest}"
    return hashlib.sha256(
        CACHE_VERSION.encode("utf-8") + processed_bytes
    ).hexdigest()[:32]


def is_valid_photo_hash(photo_hash):
    return bool(photo_hash and PHOTO_HASH_RE.fullmatch(photo_hash))


def is_profile_hash(photo_hash):
    h = photo_hash or ""
    return h.startswith("p") or h.startswith("wp")


def is_female_hash(photo_hash):
    return (photo_hash or "").startswith("w")


